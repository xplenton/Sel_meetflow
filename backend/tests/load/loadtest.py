"""Iter 344 — Unified Performance / Load test harness.

Modes:
  smoke   — 20 users × 3 rounds. Quick verification.
  load    — 100 users × 30 rounds (~5 min). Production load.
  stress  — ramp 100 → 500 in 50-user steps until error rate > 10 % or p95 > 5 s.
  soak    — 100 users continuous loops for N minutes (default 30).

Per-mode metrics:
  * Latency (avg, p50, p95, p99, max) per endpoint
  * Error rate, timeout rate, HTTP status distribution
  * Throughput (RPS), elapsed seconds
  * Backend CPU + RSS sampled every 5 s from /proc/[pid]/status
  * Memory growth (Δ RSS over the run) — flag soak leaks.
  * Auth token refresh per worker every 60 s.
  * Write endpoints exercised (POST bookings stub, POST tasks).

Reports written to /app/test_reports/perf_iter344/.

Usage:
    python3 /app/backend/tests/load/loadtest.py --mode smoke
    python3 /app/backend/tests/load/loadtest.py --mode load
    python3 /app/backend/tests/load/loadtest.py --mode stress
    python3 /app/backend/tests/load/loadtest.py --mode soak --soak-min 30
"""
